"""Builds src/GpuFsrSdlGpuShaders.hpp: GpuFsr's passes for SDL3's GPU renderer.

The pixel shaders are the Direct3D 11 ones - FSR's passes and the colour
pass (src/GpuFsrD3D11.cpp), and the graphics effects' HLSL
(src/GraphicsEffects.cpp) - so there is one copy of each. The effects are
found again at run time by a hash of their HLSL (GpuFsr::compileEffect
hands it over), so they need no shader compiler on the player's PC.

This wraps them for SDL_GPU's binding layout (texture and sampler in
space2 / descriptor set 2, the constants in space3 / set 3, the inputs
SDL's own vertex shader gives) and compiles each twice with Microsoft's
DirectX Shader Compiler: signed DXIL for Direct3D 12 and SPIR-V for Vulkan.
The Windows SDK's dxc makes no SPIR-V; the release from
https://github.com/microsoft/DirectXShaderCompiler/releases does. Run it
again after changing any of those shaders:

    python tools/build_sdlgpu_shaders.py [path/to/dxc.exe]

(without a path: ZT_DXC, then B:/zt1-tools/dxc-*/bin/x64/dxc.exe)
"""
import os
import re
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "src" / "GpuFsrSdlGpuShaders.hpp"
# (file, the string's name): the passes, then the effects (found by hash)
SHADERS = [("GpuFsrD3D11.cpp", "kEasu"), ("GpuFsrD3D11.cpp", "kRcas"), ("GpuFsrD3D11.cpp", "kStyle"),
           ("GpuFsrD3D11.cpp", "kColour")]
EFFECTS = [("GraphicsEffects.cpp", "kFxaaHlsl"), ("GraphicsEffects.cpp", "kBloomHlsl"),
           ("GraphicsEffects.cpp", "kTiltShiftHlsl"), ("GraphicsEffects.cpp", "kGradeHlsl")]

# The lighting's passes (src/shaders/*.hlsl, written for SDL_GPU's layout):
# (file, the name in the header, profile). '#include "sun"' in them becomes
# GpuSunD3D11.cpp's sun functions (kHlsl without its declarations)
LIGHTING = [("lighting_clip.comp.hlsl", "kLightingClip", "cs_6_0"),
            ("lighting_surface.vert.hlsl", "kLightingSurfaceVert", "vs_6_0"),
            ("lighting_surface.frag.hlsl", "kLightingSurfaceFrag", "ps_6_0"),
            ("lighting_ground.vert.hlsl", "kLightingGroundVert", "vs_6_0"),
            ("lighting_ground.frag.hlsl", "kLightingGroundFrag", "ps_6_0"),
            ("lighting_composite.frag.hlsl", "kLightingComposite", "ps_6_0")]

HEADER = """[[vk::binding(0, 3)]] cbuffer C : register(b0, space3) { float2 uSize; float uTime; float pad; float4 p0; float4 p1; float4 p2; float4 p3; };
[[vk::combinedImageSampler]] [[vk::binding(0, 2)]] Texture2D src : register(t0, space2);
[[vk::combinedImageSampler]] [[vk::binding(0, 2)]] SamplerState samp : register(s0, space2);
"""
# SDL's tri_texture vertex shader's outputs, in its order and as its DXIL
# names them (SDL's shaders go through SPIR-V, which renames every varying
# TEXCOORDn): a different name and Direct3D 12 won't make the pipeline.
# (Vulkan matches them by place: locations 0 and 1)
WRAP = """
struct PSInput { float4 v_color : TEXCOORD0; float2 v_uv : TEXCOORD1; float4 pos : SV_Position; };
float4 main(PSInput input) : SV_Target { return zt_main(input.pos); }
"""
ENTRY = "float4 main(float4 pos : SV_Position) : SV_Target {"
# (format, the name's ending, dxc's extra arguments)
TARGETS = [("DXIL", "Dxil", []), ("SPIR-V", "Spv", ["-spirv", "-fspv-target-env=vulkan1.0"])]


def find_dxc():
    if len(sys.argv) > 1:
        return sys.argv[1]
    if os.environ.get("ZT_DXC"):
        return os.environ["ZT_DXC"]
    found = sorted(Path("B:/zt1-tools").glob("dxc-*/bin/x64/dxc.exe"))
    if not found:
        sys.exit("dxc.exe (the GitHub release, with SPIR-V) not found: pass its path")
    return str(found[-1])


def raw(file, name):
    # (read with universal newlines: the compiler's raw string has "\n" too)
    text = (ROOT / "src" / file).read_text(encoding="utf-8")
    m = re.search(r'const char \*' + name + r' = R"\((.*?)\)";', text, re.S)
    if not m:
        sys.exit(f"{name} not found in {file}")
    return m.group(1)


def fnv1a64(s):
    h = 0xcbf29ce484222325
    for b in s.encode("utf-8"):
        h = ((h ^ b) * 0x100000001b3) & 0xffffffffffffffff
    return h


def body(src, name):
    if ENTRY not in src:
        sys.exit(f"{name}: its main isn't the expected one")
    return HEADER + src.replace(ENTRY, "float4 zt_main(float4 pos) {") + WRAP


def array(out, name, code):
    out.append(f"// {name}: {len(code)} bytes")
    out.append(f"inline constexpr unsigned char {name}[] = {{")
    for i in range(0, len(code), 20):
        out.append("  " + ", ".join(f"0x{b:02x}" for b in code[i:i + 20]) + ",")
    out.append("};")


def main():
    dxc = find_dxc()
    out = [
        "// Generated by tools/build_sdlgpu_shaders.py from src/GpuFsrD3D11.cpp's",
        "// and src/GraphicsEffects.cpp's shaders - don't edit; run the script",
        "// again. For SDL3's GPU renderer: DXIL (ps_6_0) for Direct3D 12, SPIR-V",
        "// for Vulkan.",
        "#pragma once",
        "",
        "#include <cstddef>",
        "",
        "namespace GpuFsr {",
        "namespace SdlGpu {",
    ]
    hashes = []
    with tempfile.TemporaryDirectory(dir=os.environ.get("TEMP")) as tmp:
        for file, name in SHADERS + EFFECTS:
            src = raw(file, name)
            hashes.append((name, fnv1a64(src)))
            hlsl = Path(tmp) / f"{name}.hlsl"
            hlsl.write_text(body(src, name), encoding="utf-8")
            for what, end, extra in TARGETS:
                code_file = Path(tmp) / f"{name}.{end}"
                r = subprocess.run([dxc, "-nologo", "-T", "ps_6_0", "-E", "main", "-O3", *extra, "-Fo",
                                    str(code_file), str(hlsl)], capture_output=True, text=True)
                if r.returncode != 0:
                    sys.exit(f"{name} ({what}): dxc failed\n{r.stdout}{r.stderr}")
                array(out, name + end, code_file.read_bytes())
        sun = raw("GpuSunD3D11.cpp", "kHlsl")
        sun = sun[sun.index("float sunTap("):]
        # (sunOpacity a byte buffer there: SDL_GPU binds raw views)
        assert sun.count("sunOpacity[by]") == 1
        sun = sun.replace("sunOpacity[by]", "asfloat(sunOpacity.Load(by * 4u))")
        for file, name, profile in LIGHTING:
            src = (ROOT / "src" / "shaders" / file).read_text(encoding="utf-8").replace('#include "sun"', sun)
            hlsl = Path(tmp) / file
            hlsl.write_text(src, encoding="utf-8")
            for what, end, extra in TARGETS:
                code_file = Path(tmp) / f"{name}.{end}"
                r = subprocess.run([dxc, "-nologo", "-T", profile, "-E", "main", "-O3", *extra, "-Fo",
                                    str(code_file), str(hlsl)], capture_output=True, text=True)
                if r.returncode != 0:
                    sys.exit(f"{name} ({what}): dxc failed\n{r.stdout}{r.stderr}")
                array(out, name + end, code_file.read_bytes())
    out += ["", "// A shader in both forms",
            "struct Code {", "  const unsigned char *dxil;", "  size_t dxilSize;", "  const unsigned char *spv;",
            "  size_t spvSize;", "};"]
    for name in [n for _, n in SHADERS] + [n for _, n, _ in LIGHTING]:
        out.append(f"inline constexpr Code {name}Code = {{{name}Dxil, sizeof({name}Dxil), {name}Spv, sizeof({name}Spv)}};")
    out += ["", "// The effects, by the FNV-1a hash of their HLSL",
            "struct Effect {", "  unsigned long long hash;", "  Code code;", "};",
            "inline constexpr Effect kEffects[] = {"]
    for name, h in hashes[len(SHADERS):]:
        out.append(f"  {{0x{h:016x}ull, {{{name}Dxil, sizeof({name}Dxil), {name}Spv, sizeof({name}Spv)}}}},")
    out += ["};", "} // namespace SdlGpu", "} // namespace GpuFsr", ""]
    OUT.write_bytes("\r\n".join(out).encode("utf-8"))
    print("wrote", OUT, "with", ", ".join([n for _, n in SHADERS + EFFECTS] + [n for _, n, _ in LIGHTING]), "using", dxc)


if __name__ == "__main__":
    main()
