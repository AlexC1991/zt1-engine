"""Builds src/GpuFsrSdlGpuShaders.hpp: GpuFsr's passes for SDL3's GPU renderer.

The pixel shaders are the Direct3D 11 ones (the kEasu, kRcas and kStyle
strings in src/GpuFsrD3D11.cpp), so there is one copy of each. This wraps
them for SDL_GPU's binding layout (texture and sampler in space2, the
constants in space3, the inputs SDL's own vertex shader gives) and compiles
them with the Windows SDK's dxc to signed DXIL. Run it again after changing
those shaders:

    python tools/build_sdlgpu_shaders.py [path/to/dxc.exe]
"""
import os
import re
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "src" / "GpuFsrD3D11.cpp"
OUT = ROOT / "src" / "GpuFsrSdlGpuShaders.hpp"
SHADERS = ["kEasu", "kRcas", "kStyle"]

HEADER = """cbuffer C : register(b0, space3) { float2 uSize; float uTime; float pad; float4 p0; float4 p1; float4 p2; float4 p3; };
Texture2D src : register(t0, space2);
SamplerState samp : register(s0, space2);
"""
# SDL's tri_texture vertex shader's outputs, in its order and as its DXIL
# names them (SDL's shaders go through SPIR-V, which renames every varying
# TEXCOORDn): a different name and Direct3D 12 won't make the pipeline
WRAP = """
struct PSInput { float4 v_color : TEXCOORD0; float2 v_uv : TEXCOORD1; float4 pos : SV_Position; };
float4 main(PSInput input) : SV_Target { return zt_main(input.pos); }
"""


def find_dxc():
    if len(sys.argv) > 1:
        return sys.argv[1]
    kits = Path(r"C:\Program Files (x86)\Windows Kits\10\bin")
    found = sorted(kits.glob("10.*/x64/dxc.exe"))
    if not found:
        sys.exit("dxc.exe not found: pass its path")
    return str(found[-1])


def body(text, name):
    m = re.search(r"const char \*" + name + r' = R"\((.*?)\)";', text, re.S)
    if not m:
        sys.exit(f"{name} not found in {SOURCE.name}")
    src = m.group(1)
    entry = "float4 main(float4 pos : SV_Position) : SV_Target {"
    if entry not in src:
        sys.exit(f"{name}: its main isn't the expected one")
    return HEADER + src.replace(entry, "float4 zt_main(float4 pos) {") + WRAP


def main():
    dxc = find_dxc()
    text = SOURCE.read_text(encoding="utf-8")
    out = [
        "// Generated by tools/build_sdlgpu_shaders.py from src/GpuFsrD3D11.cpp's",
        "// shaders - don't edit; run the script again. DXIL (ps_6_0) for SDL3's GPU",
        "// renderer on Direct3D 12.",
        "#pragma once",
        "",
        "namespace GpuFsr {",
        "namespace SdlGpu {",
    ]
    with tempfile.TemporaryDirectory(dir=os.environ.get("TEMP")) as tmp:
        for name in SHADERS:
            hlsl = Path(tmp) / f"{name}.hlsl"
            dxil = Path(tmp) / f"{name}.dxil"
            hlsl.write_text(body(text, name), encoding="utf-8")
            r = subprocess.run([dxc, "-nologo", "-T", "ps_6_0", "-E", "main", "-O3", "-Fo", str(dxil), str(hlsl)],
                               capture_output=True, text=True)
            if r.returncode != 0:
                sys.exit(f"{name}: dxc failed\n{r.stdout}{r.stderr}")
            code = dxil.read_bytes()
            out.append(f"// {name}: {len(code)} bytes")
            out.append(f"static const unsigned char {name}Dxil[] = {{")
            for i in range(0, len(code), 20):
                out.append("  " + ", ".join(f"0x{b:02x}" for b in code[i:i + 20]) + ",")
            out.append("};")
    out += ["} // namespace SdlGpu", "} // namespace GpuFsr", ""]
    OUT.write_bytes("\r\n".join(out).encode("utf-8"))
    print("wrote", OUT, "with", ", ".join(SHADERS))


if __name__ == "__main__":
    main()
